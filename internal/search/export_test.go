// csvTriggers are the leading characters a spreadsheet application may treat
// as the start of a formula.
var csvTriggers = []string{"=", "+", "-", "@", "\t", "\r"}

func TestCSVCell(t *testing.T) {
	for _, c := range csvTriggers {
		assert.Equal(t, "'"+c+"marker", csvCell(c+"marker"), "leading %q", c)
		assert.Equal(t, "'"+c, csvCell(c), "only %q", c)
		assert.Equal(t, "marker"+c, csvCell("marker"+c), "trailing %q", c)
	}
	for _, s := range []string{"", "marker", " =marker", "'=marker", "1+1", "<?php", "\nmarker"} {
		assert.Equal(t, s, csvCell(s))
	}
}

func TestWriteResultsCSV_NeutralizesFormulaCells(t *testing.T) {
	results := &manager.SearchResponse{}
	for _, c := range csvTriggers {
		results.Results = append(results.Results, &manager.SearchResult{
			Name:           c + "name",
			Slug:           c + "slug",
			Version:        c + "1.0",
			ActiveInstalls: -5,
			Matches: []*index.FileMatch{{
				Filename: c + "file.php",
				Matches:  []*index.Match{{Line: c + "1+1", LineNumber: 7}},
			}},
		})
	}
	results.Results = append(results.Results, &manager.SearchResult{
		Name:           "Plain, \"quoted\"",
		Slug:           "plain",
		Version:        "2.0",
		ActiveInstalls: 100,
		Matches: []*index.FileMatch{{
			Filename: "inc/plain.php",
			Matches:  []*index.Match{{Line: "    $a = $b - 1;", LineNumber: 12}},
		}},
	})

	var buf bytes.Buffer
	writeResultsCSV(&buf, results)

	rows, err := csv.NewReader(&buf).ReadAll()
	require.NoError(t, err)
	require.Len(t, rows, len(csvTriggers)+2)

	assert.Equal(t, []string{"Extension", "Slug", "Version", "Active Installs", "File", "Line Number", "Line"}, rows[0])
	for i, c := range csvTriggers {
		// The numeric columns are generated by the handler and stay as they are.
		assert.Equal(t, []string{
			"'" + c + "name",
			"'" + c + "slug",
			"'" + c + "1.0",
			"-5",
			"'" + c + "file.php",
			"7",
			"'" + c + "1+1",
		}, rows[i+1], "leading %q", c)
	}
	assert.Equal(t, []string{"Plain, \"quoted\"", "plain", "2.0", "100", "inc/plain.php", "12", "    $a = $b - 1;"}, rows[len(rows)-1])
}
